int main() {
  std::string err, what;

  // --- DEFLATE crudo: las tres clases de bloque y la copia solapada ---
  {
    std::vector<u8> out;
    check(archive::inflate(kStored, sizeof kStored, out, err), "inflate kStored");
    check(sameBytes(out, kPayload, sizeof kPayload), "contenido kStored");
  }
  {
    std::vector<u8> out;
    check(archive::inflate(kFixed, sizeof kFixed, out, err), "inflate kFixed");
    check(sameBytes(out, kAbc, sizeof kAbc), "contenido kFixed");
  }
  {
    std::vector<u8> out;
    check(archive::inflate(kDynamic, sizeof kDynamic, out, err), "inflate kDynamic");
    check(sameBytes(out, kPayload, sizeof kPayload), "contenido kDynamic");
  }
  {
    std::vector<u8> out;
    check(archive::inflate(kRle, sizeof kRle, out, err), "inflate kRle");
    check(sameBytes(out, kRlePlain, sizeof kRlePlain), "contenido kRle");
  }

  // --- un flujo truncado tiene que dar error, no basura ni desbordamiento ---
  {
    std::vector<u8> out;
    check(!archive::inflate(kDynamic, sizeof kDynamic / 2, out, err), "deflate truncado rechazado");
  }

  // --- CRC-32 (el mismo que usan zip y gzip) ---
  check(archive::crc32(kPayload, sizeof kPayload) == 0x7734bb68u, "crc32 del payload");

  // --- gzip con FEXTRA + FNAME + FCOMMENT ---
  {
    std::vector<u8> d(kGzipFlags, kGzipFlags + sizeof kGzipFlags);
    check(archive::unwrap(d, what, err), "gzip con banderas");
    check(sameBytes(d, kPayload, sizeof kPayload), "contenido gzip");
    check(what.compare(0, 4, "gzip") == 0, "gzip se anuncia como gzip");
  }
  {
    std::vector<u8> d(kGzipBadCrc, kGzipBadCrc + sizeof kGzipBadCrc);
    check(!archive::unwrap(d, what, err), "gzip con CRC roto rechazado");
  }

  // --- zip: eleccion de entrada, guardado, CRC roto y metodo no soportado ---
  {
    std::vector<u8> d(kZipPick, kZipPick + sizeof kZipPick);
    check(archive::unwrap(d, what, err), "zip con varias entradas");
    check(sameBytes(d, kPayload, sizeof kPayload), "zip elige la .z64 aunque el .txt sea mayor");
    check(what.find("juego.z64") != std::string::npos, "zip dice que entrada saco");
  }
  {
    std::vector<u8> d(kZipStored, kZipStored + sizeof kZipStored);
    check(archive::unwrap(d, what, err), "zip guardado sin comprimir");
    check(sameBytes(d, kPayload, sizeof kPayload), "contenido zip guardado");
  }
  {
    std::vector<u8> d(kZipBadCrc, kZipBadCrc + sizeof kZipBadCrc);
    check(!archive::unwrap(d, what, err), "zip con CRC roto rechazado");
  }
  {
    std::vector<u8> d(kZipMethod12, kZipMethod12 + sizeof kZipMethod12);
    check(!archive::unwrap(d, what, err), "zip con metodo 12 rechazado");
    check(err.find("12") != std::string::npos, "el error nombra el metodo");
  }

  // --- firmas que se rechazan con nombre propio ---
  {
    std::vector<u8> d = {0x37, 0x7a, 0xbc, 0xaf, 0x27, 0x1c, 0, 0};
    check(!archive::unwrap(d, what, err), "7z rechazado");
    check(err.find("7z") != std::string::npos, "el error nombra 7z");
    d = {0x52, 0x61, 0x72, 0x21, 0x1a, 0x07, 0, 0};
    check(!archive::unwrap(d, what, err), "rar rechazado");
  }

  // --- una ROM cruda no es contenedor: no se toca ---
  {
    std::vector<u8> d(kPayload, kPayload + sizeof kPayload);
    check(archive::unwrap(d, what, err), "ROM cruda aceptada");
    check(what.empty(), "ROM cruda no anuncia contenedor");
    check(sameBytes(d, kPayload, sizeof kPayload), "ROM cruda intacta");
  }

  // --- nombre de los ficheros que viven al lado de la ROM ---
  check(archive::stripContainerExt("C:/roms/mario.z64.gz") == "C:/roms/mario.z64", "gz fuera");
  check(archive::stripContainerExt("C:/roms/mario.ZIP") == "C:/roms/mario", "ZIP fuera (mayusculas)");
  check(archive::stripContainerExt("C:/roms/mario.z64") == "C:/roms/mario.z64", "z64 se queda");
  check(archive::stripContainerExt("C:/carpeta.gz/mario") == "C:/carpeta.gz/mario", "punto en la carpeta");

  std::printf(fails == 0 ? "archive_test: ALL PASS\n" : "archive_test: %d fallos\n", fails);
  return fails ? 1 : 0;
}
